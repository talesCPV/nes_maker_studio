.segment "HEADER"
  .byte $4E,$45,$53,$1A,2,1,$01,0,0,0,0,0,0,0,0,0  ; NROM-256 (32KB PRG), vertical mirroring

.segment "ZEROPAGE"
pad1:       .res 1
pad1_old:   .res 1
pad1_edge:  .res 1
game_state: .res 1    ; 0=splash 1=play 2=gameover
cur_screen: .res 1
nmi_flag:   .res 1
tmp0:       .res 1
tmp1:       .res 1
player_x:   .res 1
player_y:   .res 1
player_on:  .res 1    ; 0=oculto 1=visivel
player_flip:.res 1    ; 0=normal !=0 flip H
on_ground:  .res 1
jump_cnt:   .res 1    ; frames restantes de impulso de pulo
col_x:      .res 1    ; tile X para consulta
col_y:      .res 1    ; tile Y para consulta
col_result: .res 1
ls_count:   .res 1    ; contador load_screen (nao reusa pad)
music_on:   .res 1
ch0_timer: .res 1
ch0_pos:   .res 1
ch1_timer: .res 1
ch1_pos:   .res 1
ch2_timer: .res 1
ch2_pos:   .res 1

.segment "CODE"

NMI:
  PHA
  TXA
  PHA
  TYA
  PHA
  ; OAM DMA
  LDA #0
  STA $2003
  LDA #$02
  STA $4014
  JSR music_update
  LDA #1
  STA nmi_flag
  PLA
  TAY
  PLA
  TAX
  PLA
  RTI

IRQ:
  RTI

music_update:
  LDA music_on
  BNE mu_run
  RTS
mu_run:
mu_ch0:
  LDA ch0_timer
  BEQ mu_ch0_next
  DEC ch0_timer
  JMP mu_ch0_end
mu_ch0_next:
  LDY ch0_pos
  LDA Scale_ch0,Y
  CMP #$FF
  BNE mu_ch0_nof
  LDA #0
  STA ch0_pos
  LDY #0
  LDA Scale_ch0,Y
mu_ch0_nof:
  CMP #$FE
  BNE mu_ch0_play
  LDA #%00110000
  STA $4000
  JMP mu_ch0_end
mu_ch0_play:
  TAX
  LDA Time_ch0,Y
  STA ch0_timer
  INY
  STY ch0_pos
  CPX #0
  BNE mu_ch0_tone
  LDA #%00110000
  STA $4000
  JMP mu_ch0_end
mu_ch0_tone:
  LDA #%10111111
  STA $4000
  LDA PitchLo_ch0,X
  STA $4002
  LDA PitchHi_ch0,X
  STA $4003
mu_ch0_end:
mu_ch1:
  LDA ch1_timer
  BEQ mu_ch1_next
  DEC ch1_timer
  JMP mu_ch1_end
mu_ch1_next:
  LDY ch1_pos
  LDA Scale_ch1,Y
  CMP #$FF
  BNE mu_ch1_nof
  LDA #0
  STA ch1_pos
  LDY #0
  LDA Scale_ch1,Y
mu_ch1_nof:
  CMP #$FE
  BNE mu_ch1_play
  LDA #%00110000
  STA $4004
  JMP mu_ch1_end
mu_ch1_play:
  TAX
  LDA Time_ch1,Y
  STA ch1_timer
  INY
  STY ch1_pos
  CPX #0
  BNE mu_ch1_tone
  LDA #%00110000
  STA $4004
  JMP mu_ch1_end
mu_ch1_tone:
  LDA #%01111111
  STA $4004
  LDA PitchLo_ch1,X
  STA $4006
  LDA PitchHi_ch1,X
  STA $4007
mu_ch1_end:
mu_ch2:
  LDA ch2_timer
  BEQ mu_ch2_next
  DEC ch2_timer
  JMP mu_ch2_end
mu_ch2_next:
  LDY ch2_pos
  LDA Scale_ch2,Y
  CMP #$FF
  BNE mu_ch2_nof
  LDA #0
  STA ch2_pos
  LDY #0
  LDA Scale_ch2,Y
mu_ch2_nof:
  CMP #$FE
  BNE mu_ch2_play
  LDA #%00000000
  STA $4008
  JMP mu_ch2_end
mu_ch2_play:
  TAX
  LDA Time_ch2,Y
  STA ch2_timer
  INY
  STY ch2_pos
  CPX #0
  BNE mu_ch2_tone
  LDA #%00000000
  STA $4008
  JMP mu_ch2_end
mu_ch2_tone:
  LDA #%11111111
  STA $4008
  LDA PitchLo_ch2,X
  STA $400A
  LDA PitchHi_ch2,X
  STA $400B
mu_ch2_end:
  RTS

music_init:
  LDA #0
  STA ch0_timer
  STA ch0_pos
  STA ch1_timer
  STA ch1_pos
  STA ch2_timer
  STA ch2_pos
  LDA #$0F
  STA $4015
  LDA #1
  STA music_on
  RTS

; Leitura do controle P1 (strobe padrão NES)
read_pad:
  LDA pad1
  STA pad1_old
  LDA #1
  STA $4016
  LDA #0
  STA $4016
  LDX #8
  LDA #0
  STA pad1
rp_loop:
  LDA $4016
  AND #1
  LSR A
  ROR pad1
  DEX
  BNE rp_loop
  ; edge = pad1 & ~pad1_old
  LDA pad1_old
  EOR #$FF
  AND pad1
  STA pad1_edge
  RTS

; Carrega nametable+attrs da tela A (hard cut, rendering off)
load_screen:
  STA cur_screen
  ; desliga rendering
  LDA #0
  STA $2001
  ; ponteiro da nametable (tabela de 1 byte por tela — SEM ASL)
  LDX cur_screen
  LDA ScreenNtLo,X
  STA tmp0
  LDA ScreenNtHi,X
  STA tmp1
  BIT $2002
  LDA #$20
  STA $2006
  LDA #$00
  STA $2006
  LDY #0
  LDX #4          ; 4×240 = 960 tiles
ls_nt_outer:
  LDA #240
  STA ls_count
ls_nt_inner:
  LDA (tmp0),Y
  STA $2007
  INY
  BNE ls_nt_noinc
  INC tmp1
ls_nt_noinc:
  DEC ls_count
  BNE ls_nt_inner
  DEX
  BNE ls_nt_outer
  ; attributes
  LDX cur_screen
  LDA ScreenAtLo,X
  STA tmp0
  LDA ScreenAtHi,X
  STA tmp1
  BIT $2002
  LDA #$23
  STA $2006
  LDA #$C0
  STA $2006
  LDY #0
ls_at:
  LDA (tmp0),Y
  STA $2007
  INY
  CPY #64
  BNE ls_at
  ; scroll zerado
  BIT $2002
  LDA #0
  STA $2005
  STA $2005
  ; religa rendering (bg + sprites)
  LDA #%00011110
  STA $2001
  RTS

update_player_oam:
  LDA player_on
  BNE upo_draw
  ; esconde: Y=$FF nos 4 slots
  LDA #$FF
  STA $0200
  STA $0204
  STA $0208
  STA $020C
  RTS
upo_draw:
  LDA player_flip
  BEQ upo_noflip
  LDA #%01000000     ; flip H
  STA tmp0
  JMP upo_attr
upo_noflip:
  LDA #0
  STA tmp0
upo_attr:
  ; sprite 0: topo-esq
  LDA player_y
  STA $0200
  LDA #0              ; tile 0
  STA $0201
  LDA tmp0
  STA $0202
  LDA player_x
  STA $0203
  ; sprite 1: topo-dir
  LDA player_y
  STA $0204
  LDA #1              ; tile 1
  STA $0205
  LDA tmp0
  STA $0206
  LDA player_x
  CLC
  ADC #8
  STA $0207
  ; sprite 2: baixo-esq
  LDA player_y
  CLC
  ADC #8
  STA $0208
  LDA #16             ; tile 16
  STA $0209
  LDA tmp0
  STA $020A
  LDA player_x
  STA $020B
  ; sprite 3: baixo-dir
  LDA player_y
  CLC
  ADC #8
  STA $020C
  LDA #17             ; tile 17
  STA $020D
  LDA tmp0
  STA $020E
  LDA player_x
  CLC
  ADC #8
  STA $020F
  ; se flip H, troca tiles L/R para o personagem não ficar invertido só no eixo
  LDA player_flip
  BEQ upo_done
  LDA #1
  STA $0201
  LDA #0
  STA $0205
  LDA #17
  STA $0209
  LDA #16
  STA $020D
upo_done:
  RTS

spawn_player:
  LDA #40             ; X inicial
  STA player_x
  LDA #160            ; Y inicial
  STA player_y
  LDA #0
  STA player_flip
  STA jump_cnt
  STA on_ground
  LDA #1
  STA player_on
  JSR update_player_oam
  RTS

hide_player:
  LDA #0
  STA player_on
  JSR update_player_oam
  RTS

get_collision:
  LDA col_y
  CMP #30
  BCS gc_oob
  LDA col_x
  CMP #32
  BCS gc_oob
  ; offset low = (col_y & 7)*32 + col_x ; page = col_y >> 3
  LDA col_y
  AND #7
  ASL A
  ASL A
  ASL A
  ASL A
  ASL A
  CLC
  ADC col_x
  TAY
  LDX cur_screen
  LDA ScreenColLo,X
  STA tmp0
  LDA ScreenColHi,X
  STA tmp1
  LDA col_y
  LSR A
  LSR A
  LSR A
  CLC
  ADC tmp1
  STA tmp1
  LDA (tmp0),Y
  STA col_result
  RTS
gc_oob:
  LDA #0
  STA col_result
  RTS

check_ground:
  LDA #0
  STA on_ground
  ; tile Y = (player_y + 16) / 8
  LDA player_y
  CLC
  ADC #16
  LSR A
  LSR A
  LSR A
  STA col_y
  ; tile X esquerdo
  LDA player_x
  CLC
  ADC #2
  LSR A
  LSR A
  LSR A
  STA col_x
  JSR get_collision
  LDA col_result
  CMP #1
  BEQ cg_yes
  CMP #2
  BEQ cg_yes
  ; tile X direito
  LDA player_x
  CLC
  ADC #13
  LSR A
  LSR A
  LSR A
  STA col_x
  JSR get_collision
  LDA col_result
  CMP #1
  BEQ cg_yes
  CMP #2
  BEQ cg_yes
  RTS
cg_yes:
  LDA #1
  STA on_ground
  ; snap Y ao topo do tile
  LDA col_y
  ASL A
  ASL A
  ASL A
  SEC
  SBC #16
  STA player_y
  RTS

update_player:
  LDA player_on
  BNE up_go
  RTS
up_go:
  ; --- horizontal (pad level, nao so edge) ---
  LDA pad1
  AND #%01000000      ; Left bit6
  BEQ up_right
  LDA player_x
  CMP #3
  BCC up_right
  SEC
  SBC #3
  STA player_x
  LDA #1
  STA player_flip
up_right:
  LDA pad1
  AND #%10000000      ; Right bit7
  BEQ up_jump
  LDA player_x
  CMP #237
  BCS up_jump
  CLC
  ADC #3
  STA player_x
  LDA #0
  STA player_flip
up_jump:
  ; B ou A (edge) + on_ground → pulo
  LDA pad1_edge
  AND #%00000011      ; A ou B
  BEQ up_vert
  LDA on_ground
  BEQ up_vert
  LDA #14
  STA jump_cnt
  LDA #0
  STA on_ground
up_vert:
  LDA jump_cnt
  BEQ up_fall
  DEC jump_cnt
  LDA player_y
  SEC
  SBC #4
  BCS up_jok
  LDA #0
up_jok:
  STA player_y
  JMP up_done
up_fall:
  JSR check_ground
  LDA on_ground
  BNE up_done
  LDA player_y
  CLC
  ADC #4
  STA player_y
  CMP #240
  BCC up_done
  ; caiu → respawn
  LDA #40
  STA player_x
  LDA #32
  STA player_y
  LDA #0
  STA jump_cnt
up_done:
  JSR update_player_oam
  RTS

Reset:
  SEI
  CLD
  LDX #$40
  STX $4017
  LDX #$FF
  TXS
  INX                ; X=0
  STX $2000
  STX $2001
  STX $4010
vblankwait1:
  BIT $2002
  BPL vblankwait1
  ; clear RAM $0000-$07FF
  LDA #0
  TAX
clrram:
  STA $0000,X
  STA $0100,X
  STA $0200,X
  STA $0300,X
  STA $0400,X
  STA $0500,X
  STA $0600,X
  STA $0700,X
  INX
  BNE clrram
vblankwait2:
  BIT $2002
  BPL vblankwait2
  ; paletas
  BIT $2002
  LDA #$3F
  STA $2006
  LDA #$00
  STA $2006
  LDX #0
loadpal:
  LDA PaletteData,X
  STA $2007
  INX
  CPX #32
  BNE loadpal
  ; OAM off-screen
  LDX #0
  LDA #$FF
clroam:
  STA $0200,X
  INX
  BNE clroam
  ; splash = tela 0
  LDA #0
  STA game_state
  STA player_on
  LDA #0
  JSR load_screen
  JSR music_init
  ; scroll 0,0
  LDA #0
  STA $2005
  STA $2005
  ; NMI on, bg @$1000, sprites @$0000
  LDA #%10010000
  STA $2000
  LDA #%00011110
  STA $2001

; ---- Main loop ----
; Bits do pad (após ROR x8): A=0 B=1 Select=2 Start=3 Up=4 Down=5 Left=6 Right=7
; START no splash → Fase 1 + spawn Hero
; SELECT no play → Game Over (atalho de teste)
MainLoop:
  LDA nmi_flag
  BEQ MainLoop
  LDA #0
  STA nmi_flag
  JSR read_pad
  LDA game_state
  CMP #0
  BEQ st_splash
  CMP #1
  BEQ st_play
  JMP st_gameover

st_splash:
  ; bit 3 = START
  LDA pad1_edge
  AND #%00001000
  BEQ MainLoop
  LDA #1
  STA game_state
  LDA #1
  JSR load_screen
  JSR spawn_player
  JSR music_init
  JMP MainLoop

st_play:
  ; fisica + input todo frame (Camada 2)
  JSR update_player
  ; SELECT → Game Over (teste)
  LDA pad1_edge
  AND #%00000100
  BEQ st_play_done
  LDA #2
  STA game_state
  JSR hide_player
  LDA #6
  JSR load_screen
st_play_done:
  JMP MainLoop

st_gameover:
  ; START no game over → volta pro splash
  LDA pad1_edge
  AND #%00001000
  BEQ MainLoop
  LDA #0
  STA game_state
  JSR hide_player
  LDA #0
  JSR load_screen
  JMP MainLoop

